    def test_complete_corpus_reconstructs_and_rejects_attempt_tampering(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            output, plan_path = self.complete_corpus_fixture(Path(raw))
            verified = MODULE.validate_corpus(output, plan_path)
            self.assertTrue(verified["verified"])
            self.assertEqual(verified["item_count"], 49)
            attempt_path = output / "attempt.json"
            attempt = json.loads(attempt_path.read_bytes())
            attempt["timeout_seconds_per_precompression_operation"] = False
            attempt_path.write_bytes(MODULE.json_bytes(attempt))
            with self.assertRaisesRegex(ValueError, "corpus identity differs"):
                MODULE.validate_corpus(output, plan_path)

    def test_complete_corpus_rejects_a_malformed_process_commitment(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            output, plan_path = self.complete_corpus_fixture(Path(raw))
            receipt_path = output / "receipts" / "precompressed-00.json"
            receipt = json.loads(receipt_path.read_bytes())
            receipt["compression"]["stdout"]["extra"] = 1
            receipt_path.write_bytes(MODULE.json_bytes(receipt))
            with self.assertRaisesRegex(ValueError, "process differs"):
                MODULE.validate_corpus(output, plan_path)

    def test_toolchain_identity_is_strict_and_tamper_evident(self) -> None:
        fixture = self.toolchain_fixture()
        MODULE.validate_toolchain(fixture)
        cases = []
        extra = copy.deepcopy(fixture)
        extra["unexpected"] = {}
        cases.append(extra)
        boolean_size = copy.deepcopy(fixture)
        boolean_size["gzip"]["binary_size_bytes"] = True
        cases.append(boolean_size)
        uppercase_digest = copy.deepcopy(fixture)
        uppercase_digest["python-zipfile"]["runner_sha256"] = "A" * 64
        cases.append(uppercase_digest)
        wrong_chunk = copy.deepcopy(fixture)
        wrong_chunk["corpus-builder"]["stream_chunk_bytes"] = MODULE.CHUNK_SIZE - 1
        cases.append(wrong_chunk)
        for case in cases:
            with self.subTest(case=case):
                with self.assertRaisesRegex(ValueError, "toolchain|tool identity|ZIP|builder"):
                    MODULE.validate_toolchain(case)

    def test_stream_commitments_have_an_exact_schema(self) -> None:
        valid = {"bytes": 0, "sha256": hashlib.sha256(b"").hexdigest()}
        self.assertTrue(MODULE.is_stream_commitment(valid))
        self.assertFalse(MODULE.is_stream_commitment(valid | {"extra": 1}))
        self.assertFalse(
            MODULE.is_stream_commitment({"bytes": False, "sha256": valid["sha256"]})
        )
        self.assertFalse(
            MODULE.is_stream_commitment({"bytes": 0, "sha256": valid["sha256"].upper()})
        )

    def test_counter_mode_shake_is_exact_and_domain_separated(self) -> None:
        first = MODULE.shake_block("domain-a", "item-a", 0, 1024)
        self.assertEqual(len(first), 1024)
        self.assertEqual(first, MODULE.shake_block("domain-a", "item-a", 0, 1024))
        self.assertNotEqual(first, MODULE.shake_block("domain-b", "item-a", 0, 1024))
        self.assertNotEqual(first, MODULE.shake_block("domain-a", "item-b", 0, 1024))
        self.assertNotEqual(first, MODULE.shake_block("domain-a", "item-a", 1, 1024))
        with self.assertRaisesRegex(ValueError, "outside protocol"):
            MODULE.shake_block("domain", "item", -1, 1)

