    def test_zip_profile_is_deterministic_streaming_and_exact(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            source = root / "source.bin"
            source.write_bytes((b"deterministic ZIP fixture\n" * 10_000) + bytes(range(256)))
            first = root / "first.zip"
            second = root / "second.zip"
            MODULE.zip_compress(source, first)
            MODULE.zip_compress(source, second)
            self.assertEqual(first.read_bytes(), second.read_bytes())
            restored = root / "restored.bin"
            MODULE.zip_decompress(first, restored)
            self.assertEqual(source.read_bytes(), restored.read_bytes())

    def test_zip_decoder_rejects_a_roundtrippable_non_profile_archive(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            source = root / "source.bin"
            source.write_bytes(b"roundtrippable but wrong ZIP profile" * 100)
            wrong_method = root / "stored.zip"
            with MODULE.zipfile.ZipFile(
                wrong_method, "w", compression=MODULE.zipfile.ZIP_STORED
            ) as archive:
                info = MODULE.zipfile.ZipInfo(
                    "input.bin", date_time=(1980, 1, 1, 0, 0, 0)
                )
                info.compress_type = MODULE.zipfile.ZIP_STORED
                info.create_system = 0
                info.external_attr = 0x20
                archive.writestr(info, source.read_bytes())
            with self.assertRaisesRegex(ValueError, "metadata differs"):
                MODULE.zip_decompress(wrong_method, root / "restored.bin")

            archive_comment = root / "comment.zip"
            MODULE.zip_compress(source, archive_comment)
            with MODULE.zipfile.ZipFile(archive_comment, "a") as archive:
                archive.comment = b"not permitted"
            with self.assertRaisesRegex(ValueError, "metadata differs"):
                MODULE.zip_decompress(archive_comment, root / "comment-restored.bin")

