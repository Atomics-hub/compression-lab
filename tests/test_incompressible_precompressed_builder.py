    def test_tool_resolver_receives_the_frozen_baseline_config_contract(self) -> None:
        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            resolved = {}
            for tool_id in MODULE.TOOL_FOR_PROFILE.values():
                path = root / tool_id
                path.write_bytes(tool_id.encode("ascii"))
                path.chmod(0o755)
                resolved[tool_id] = {
                    "path": str(path),
                    "version": f"{tool_id} fixture",
                    "binary_size_bytes": path.stat().st_size,
                    "binary_sha256": MODULE.sha256_file(path),
                }
            with mock.patch.object(
                MODULE.BASELINE, "resolve_tools", return_value=resolved
            ) as resolver:
                paths, public = MODULE.safe_tool_records(root / "tools")
            resolver.assert_called_once()
            config, config_path, tools_root = resolver.call_args.args
            self.assertEqual(
                config["name"], "text-source-baseline-toolchain-v1"
            )
            self.assertEqual(config_path, MODULE.BASELINE.DEFAULT_CONFIG)
            self.assertEqual(tools_root, root / "tools")
            self.assertEqual(set(paths), set(MODULE.TOOL_FOR_PROFILE.values()))
            self.assertIn("python-zipfile", public)
            self.assertIn("corpus-builder", public)

